                        'Никогда не лжёт о фактах. Может соврать о мотивах, о чувствах, о планах.',
                        'Никогда не отступает при свидетелях. Отступить можно — но потом, тихо.',
                        'Никогда не появляется на встрече трезвой. Это метод: трезвая она слишком злая.',
                    ),
                ],
            ],
        ];

        $clans = CanonClan::query()->pluck('id', 'slug');
        $sects = CanonSect::query()->pluck('id', 'slug');

        return collect($definitions)->map(function (array $def) use ($chronicle, $clans, $sects, $storyteller): Character {
            $entity = WorldEntity::query()->create([
                'chronicle_id' => $chronicle->id,
                'entity_type' => WorldEntityType::Character,
                'canonical_name' => $def['name'],
                'slug' => Str::slug($def['name']).'-'.random_int(1000, 9999),
                'status' => WorldEntityStatus::Active,
            ]);

            $character = Character::query()->create([
                'id' => $entity->id,
                'chronicle_id' => $chronicle->id,
                'character_type' => CharacterType::Npc,
                'clan_id' => $clans[$def['clan_slug']] ?? null,
                'sect_id' => $sects[$def['sect_slug']] ?? null,
                'nature' => $def['nature'],
                'demeanor' => $def['demeanor'],
                'concept' => $def['concept'],
                'generation' => $def['generation'],
                'is_active' => true,
            ]);

            foreach ($def['traits'] as $i => [$key, $label, $value]) {
                CharacterTrait::query()->create([
                    'character_id' => $character->id,
                    'key' => $key,
                    'label' => $label,
                    'value' => $value,
                    'sort_order' => $i * 10,
                ]);
            }

            $bio = $def['bio'];

            CharacterBiography::query()->create([
                'character_id' => $character->id,
                'summary' => $bio['summary'],
                'full_text' => $bio['full_text'],
                'principles' => $bio['principles'],
                'motivation' => $bio['motivation'],
                'fears' => $bio['fears'],
                'desires' => $bio['desires'],
                'behavioral_rules' => $bio['behavioral_rules'],
                'current_version' => 1,
                'status' => 'approved',
                'approved_at' => now(),
                'approved_by' => $storyteller->id,
            ]);

            DB::table('character_biography_versions')->insert([
                'character_id' => $character->id,
                'version' => 1,
                'summary' => $bio['summary'],
                'full_text' => $bio['full_text'],
                'principles' => $bio['principles'],
                'motivation' => $bio['motivation'],
                'fears' => $bio['fears'],
                'desires' => $bio['desires'],
                'behavioral_rules' => $bio['behavioral_rules'],
                'change_reason' => 'Первичное заполнение (DemoSeeder)',
                'created_by' => $storyteller->id,
            ]);

            return $character;
        });
    }

    /**
     * Склеивает список: каждый пункт с новой строки, с префиксом «— ».
     */
    private function lines(string ...$items): string
    {
        return implode("\n", array_map(fn (string $i): string => '— '.$i, $items));
    }
