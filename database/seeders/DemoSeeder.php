     * Склеивает список: каждый пункт с новой строки, с префиксом «— ».
     */
    private function lines(string ...$items): string
    {
        return implode("\n", array_map(fn (string $i): string => '— '.$i, $items));
    }

    /**
     * В одинарных кавычках '\n' остаётся двумя символами; в full_text в сидере так заданы абзацы.
     */
    private function prose(string $text): string
    {
        return str_replace('\n', "\n", $text);
    }
